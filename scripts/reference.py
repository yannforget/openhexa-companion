"""Generate the CLI and MCP references in docs/ from the code.

Run `uv run python scripts/reference.py` after changing a command or a tool. A test
fails when the files in docs/ are out of date.
"""

import asyncio
import json
import re
import sys
from pathlib import Path
from typing import Any

import click
from mcp.server.mcpserver import MCPServer
from mcp_types import Tool

from openhexa.companion.cli import main as cli
from openhexa.companion.server.config import Config
from openhexa.companion.server.store import Store
from openhexa.companion.server.tools import Access, register_tools

# Options every command has, documented once at the top of the CLI reference.
COMMON = {"--help", "--json"}
DOCS = Path(__file__).parent.parent / "docs"
NOTICE = "<!-- Generated by scripts/reference.py: do not edit. -->"

# Sections of the MCP reference, with words of the tool names they hold. A tool goes in the
# first section that matches.
TOOL_AREAS = {
    "Workspaces": ("workspace", "search"),
    "Datasets": ("dataset",),
    "Database": ("database", "saved_quer"),
    "Pipelines": ("pipeline",),
    "Webapps": ("webapp",),
}


def cli_reference() -> str:
    root = click.Context(cli, info_name="hexa")
    lines = [
        NOTICE,
        "",
        "# CLI reference",
        "",
        "Every command of `hexa`, as printed by `hexa <command> --help`. Every command",
        "also accepts `--json` and `--help`. See the [README](../README.md#the-hexa-cli) to",
        "install and configure `hexa`.",
        "",
        *[
            f"- [`hexa {name}`](#hexa-{name}): {_summary(command.help)}"
            for name, command in cli.commands.items()
        ],
        "",
        "## `hexa`",
        "",
        *_entry(cli, root),
    ]
    for name, command in cli.commands.items():
        lines += _command(command, click.Context(command, info_name=name, parent=root), 2)
    return _finish(lines)


def _command(command: click.Command, ctx: click.Context, level: int) -> list[str]:
    """A heading for each group and top-level command, and an entry for each command."""
    heading = ["", f"{'#' * level} `{ctx.command_path}`", ""]
    if not isinstance(command, click.Group):
        return [*(heading if level == 2 else [""]), *_entry(command, ctx)]
    lines = [*heading, _text(command.help), ""]
    for name, sub in command.commands.items():
        lines += _command(sub, click.Context(sub, info_name=name, parent=ctx), level + 1)
    return lines


def _entry(command: click.Command, ctx: click.Context) -> list[str]:
    """The usage of `command` in bold, its help, then its options."""
    pieces = [p for p in command.collect_usage_pieces(ctx) if p != "[OPTIONS]"]
    usage = " ".join([ctx.command_path, *pieces])
    return [f"**`{usage}`**", "", _text(command.help), "", *_options(command, ctx)]


def _options(command: click.Command, ctx: click.Context) -> list[str]:
    lines = []
    for param in command.get_params(ctx):
        record = param.get_help_record(ctx)
        if isinstance(param, click.Option) and record and param.opts[0] not in COMMON:
            names, help_text = record
            lines.append(f"- `{names}`: {_oneline(help_text)}")
    return lines


def mcp_reference() -> str:
    tools = _tools()
    lines = [
        NOTICE,
        "",
        "# MCP tool reference",
        "",
        "Every tool of the MCP server, with the description AI clients see. Tools marked",
        "**write** change the workspace; the others only read. See [MCP](mcp.md) for how",
        "access works.",
        "",
        *[f"- [{area}](#{area.lower()})" for area in TOOL_AREAS],
    ]
    for area in TOOL_AREAS:
        lines += ["", f"## {area}"]
        for tool in tools:
            if _area(tool.name) == area:
                lines += _tool(tool)
    return _finish(lines)


def _tools() -> list[Tool]:
    config = Config("http://localhost", "http://localhost", "x" * 32, ":memory:")
    server = MCPServer(name="reference")
    register_tools(server, Access(config, Store(":memory:", config.fernet_key()), None))
    tools = asyncio.run(server.list_tools())
    if unplaced := [tool.name for tool in tools if _area(tool.name) is None]:
        raise SystemExit(f"Add these tools to TOOL_AREAS: {', '.join(unplaced)}")
    return sorted(tools, key=lambda tool: not _read_only(tool))


def _read_only(tool: Tool) -> bool:
    return bool(tool.annotations and tool.annotations.read_only_hint)


def _area(name: str) -> str | None:
    """The first area of `TOOL_AREAS` with a word in the tool name `name`."""
    return next((area for area, words in TOOL_AREAS.items() if any(w in name for w in words)), None)


def _tool(tool: Tool) -> list[str]:
    kind = " (**write**)" if not _read_only(tool) else ""
    # Descriptions are plain text, written for models: escape what Markdown would hide.
    description = re.sub(r"([*<])", r"\\\1", _text(tool.description))
    lines = ["", f"**`{tool.name}`**{kind}", "", description, ""]
    schema = tool.input_schema
    defs = schema.get("$defs", {})
    required = set(schema.get("required", []))
    for name, prop in schema.get("properties", {}).items():
        if name in required:
            presence = "required"
        elif prop.get("default") is not None:
            presence = f"default `{json.dumps(prop['default'])}`"
        else:
            presence = "optional"
        description = _oneline(prop.get("description", ""))
        lines.append(f"- `{name}` ({_type(prop, defs)}, {presence}): {description}")
    return lines


def _type(prop: dict[str, Any], defs: dict[str, Any]) -> str:
    """Describe a JSON schema in a few words, such as `integer (1-100)`."""
    if "anyOf" in prop:
        kinds = [_type(p, defs) for p in prop["anyOf"] if p.get("type") != "null"]
        return " or ".join(kinds)
    if "$ref" in prop:
        name = prop["$ref"].rsplit("/", 1)[-1]
        return "JSON" if name == "JsonValue" else _type(defs[name], defs)
    if "enum" in prop:
        return " | ".join(f"`{value}`" for value in prop["enum"])
    kind = prop.get("type", "any")
    if kind == "array":
        return f"list of {_type(prop.get('items', {}), defs)}"
    if kind == "object":
        return "object"
    low, high = prop.get("minimum"), prop.get("maximum")
    if low is not None and high is not None:
        return f"{kind} ({low}-{high})"
    if low is not None:
        return f"{kind} (≥ {low})"
    return kind


def _text(text: str | None) -> str:
    """Docstring or help text as Markdown paragraphs."""
    return "\n".join(line.strip() for line in (text or "").strip().splitlines())


def _finish(lines: list[str]) -> str:
    """Join `lines`, with at most one blank line in a row and a final newline."""
    return re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).strip() + "\n"


def _summary(text: str | None) -> str:
    """First paragraph of a docstring, on one line."""
    return _oneline(_text(text).split("\n\n")[0])


def _oneline(text: str) -> str:
    return " ".join(text.split())


REFERENCES = {"cli.md": cli_reference, "mcp-tools.md": mcp_reference}


if __name__ == "__main__":
    for filename, generate in REFERENCES.items():
        (DOCS / filename).write_text(generate(), encoding="utf-8")
        sys.stdout.write(f"Wrote docs/{filename}\n")
